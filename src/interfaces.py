"""
Interfaces the pipeline depends on. Concrete implementations are injected into `TrustRAGService`, so the
pipeline doesn't care whether Claude is reached through the API, a subscription or a recorded replay, or
whether chunks live in ChromaDB or an in-memory store - and tests need no monkeypatching.
"""

from typing import Protocol

from src.llm import LLMClient
from src.models import Chunk, Principal, RetrievedChunk, SessionInfo

__all__ = ["Authenticator", "LLMClient", "VectorStore"]


class VectorStore(Protocol):
    def new_workspace(self, *, persistent: bool = False) -> str: ...
    def add_chunks(self, workspace: str, chunks: list[Chunk]) -> None: ...
    def retrieve(self, workspace: str, question: str, top_k: int) -> list[RetrievedChunk]: ...
    def all_chunks(self, workspace: str) -> list[Chunk]: ...
    def delete_file(self, workspace: str, file_name: str) -> None: ...
    def list_files(self, workspace: str) -> list[str]: ...
    def count(self, workspace: str) -> int: ...
    def clear(self, workspace: str) -> None: ...
    def cleanup(self, *, keep: frozenset[str] = frozenset(), purge: frozenset[str] = frozenset()) -> int: ...


class Authenticator(Protocol):
    """Turns bearer tokens into principals. Kept behind a Protocol so the service is testable without SQLite."""

    def resolve(self, token: str) -> Principal | None: ...
    def start_session(
        self, account_id: str, username: str | None = None, *, expected_hash: str | None = None
    ) -> SessionInfo: ...
    def logout(self, token: str) -> None: ...
